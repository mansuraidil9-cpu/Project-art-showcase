-- Jalankan pada database khusus art_showcase. Tidak menghapus data yang sudah ada.
BEGIN;
CREATE TABLE IF NOT EXISTS users (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email varchar(254) NOT NULL CHECK (email = lower(btrim(email)) AND position('@' in email) > 1),
 password_hash varchar(60) NOT NULL CHECK (password_hash ~ '^\$2[aby]\$'),
 display_name varchar(80) NOT NULL CHECK (length(btrim(display_name)) BETWEEN 2 AND 80),
 role varchar(10) NOT NULL CHECK (role IN ('admin','member','curator')),
 curator_status varchar(10),
 rejection_reason text,
 avatar_path text,
 bio varchar(500) NOT NULL DEFAULT '',
 website_url text,
 instagram_url text,
 behance_url text,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT users_email_unique UNIQUE(email),
 CONSTRAINT users_curator_status_check CHECK (
 (role = 'curator' AND curator_status IS NOT NULL AND curator_status IN ('pending','approved','rejected'))
 OR (role <> 'curator' AND curator_status IS NULL)),
 CHECK (curator_status IS DISTINCT FROM 'rejected' OR length(btrim(coalesce(rejection_reason,''))) > 0)
);
CREATE TABLE IF NOT EXISTS categories (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(60) NOT NULL CHECK (name = btrim(name) AND length(name) > 0),
 description varchar(250) NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX IF NOT EXISTS categories_name_unique ON categories(lower(name));
CREATE TABLE IF NOT EXISTS artworks (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 category_id integer NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
 title varchar(150) NOT NULL CHECK (length(btrim(title)) > 0),
 description text NOT NULL CHECK (length(btrim(description)) > 0),
 file_path text NOT NULL CHECK (length(btrim(file_path)) > 0),
 media_type varchar(60) NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(id, member_id)
);
CREATE TABLE IF NOT EXISTS tags (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(40) NOT NULL UNIQUE CHECK (name = lower(btrim(name)) AND length(name) > 0)
);
CREATE TABLE IF NOT EXISTS artwork_tags (
 artwork_id integer NOT NULL REFERENCES artworks(id) ON DELETE CASCADE,
 tag_id integer NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
 PRIMARY KEY(artwork_id,tag_id)
);
CREATE TABLE IF NOT EXISTS likes (
 member_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 artwork_id integer NOT NULL REFERENCES artworks(id) ON DELETE CASCADE,
 created_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(member_id,artwork_id)
);
CREATE TABLE IF NOT EXISTS favorites (
 member_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 artwork_id integer NOT NULL REFERENCES artworks(id) ON DELETE CASCADE,
 created_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(member_id,artwork_id)
);
CREATE TABLE IF NOT EXISTS comments (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 artwork_id integer NOT NULL REFERENCES artworks(id) ON DELETE CASCADE,
 body varchar(1000) NOT NULL CHECK (length(btrim(body)) > 0),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS reports (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 artwork_id integer NOT NULL REFERENCES artworks(id) ON DELETE CASCADE,
 reason varchar(40) NOT NULL CHECK (reason IN ('SARA','Plagiat','Konten Tidak Pantas','Lainnya')),
 details varchar(1000) NOT NULL CHECK (length(btrim(details)) > 0),
 status varchar(10) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','dismissed')),
 reviewed_by integer REFERENCES users(id) ON DELETE SET NULL,
 reviewed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(member_id,artwork_id),
 CHECK ((status='pending' AND reviewed_at IS NULL) OR (status='dismissed' AND reviewed_at IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS challenges (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 curator_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 title varchar(150) NOT NULL CHECK (length(btrim(title)) > 0),
 description text NOT NULL CHECK (length(btrim(description)) > 0),
 rules text NOT NULL CHECK (length(btrim(rules)) > 0),
 prize text NOT NULL CHECK (length(btrim(prize)) > 0),
 starts_at timestamptz NOT NULL,
 ends_at timestamptz NOT NULL,
 banner_path text NOT NULL CHECK (length(btrim(banner_path)) > 0),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (ends_at > starts_at)
);
CREATE TABLE IF NOT EXISTS submissions (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 challenge_id integer NOT NULL REFERENCES challenges(id) ON DELETE CASCADE,
 member_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 artwork_id integer NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY (artwork_id,member_id) REFERENCES artworks(id,member_id) ON DELETE CASCADE,
 UNIQUE(challenge_id,member_id),
 UNIQUE(id,challenge_id)
);
CREATE TABLE IF NOT EXISTS winners (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 challenge_id integer NOT NULL REFERENCES challenges(id) ON DELETE CASCADE,
 submission_id integer NOT NULL,
 rank smallint NOT NULL CHECK(rank BETWEEN 1 AND 3),
 created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(submission_id,challenge_id) REFERENCES submissions(id,challenge_id) ON DELETE CASCADE,
 UNIQUE(challenge_id,rank),
 UNIQUE(submission_id)
);
CREATE INDEX IF NOT EXISTS artworks_member_idx ON artworks(member_id);
CREATE INDEX IF NOT EXISTS artworks_category_idx ON artworks(category_id);
CREATE INDEX IF NOT EXISTS artworks_created_idx ON artworks(created_at DESC);
CREATE INDEX IF NOT EXISTS artwork_tags_tag_idx ON artwork_tags(tag_id);
CREATE INDEX IF NOT EXISTS likes_artwork_idx ON likes(artwork_id);
CREATE INDEX IF NOT EXISTS favorites_artwork_idx ON favorites(artwork_id);
CREATE INDEX IF NOT EXISTS comments_artwork_idx ON comments(artwork_id);
CREATE INDEX IF NOT EXISTS reports_queue_idx ON reports(status,artwork_id);
CREATE INDEX IF NOT EXISTS reports_member_idx ON reports(member_id);
CREATE INDEX IF NOT EXISTS challenges_curator_idx ON challenges(curator_id);
CREATE INDEX IF NOT EXISTS challenges_dates_idx ON challenges(starts_at,ends_at);
CREATE INDEX IF NOT EXISTS submissions_artwork_idx ON submissions(artwork_id);
CREATE INDEX IF NOT EXISTS submissions_member_idx ON submissions(member_id);
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END;
$$;
DROP TRIGGER IF EXISTS users_updated_at ON users;
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS artworks_updated_at ON artworks;
CREATE TRIGGER artworks_updated_at BEFORE UPDATE ON artworks FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS challenges_updated_at ON challenges;
CREATE TRIGGER challenges_updated_at BEFORE UPDATE ON challenges FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE OR REPLACE FUNCTION prevent_artwork_file_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.file_path IS DISTINCT FROM OLD.file_path OR NEW.media_type IS DISTINCT FROM OLD.media_type THEN
  RAISE EXCEPTION 'File karya tidak dapat diganti.' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS artworks_file_immutable ON artworks;
CREATE TRIGGER artworks_file_immutable BEFORE UPDATE ON artworks FOR EACH ROW EXECUTE FUNCTION prevent_artwork_file_change();
COMMIT;

